def match_product_alias(text: str) -> List[str]:
    """从文本中匹配产品别名，返回匹配到的标准产品名列表（按出现顺序去重）。"""
    text_lower = text.lower()
    matched: List[str] = []
    seen: Set[str] = set()
    for alias, product in ALIAS_TO_PRODUCT.items():
        if alias in text_lower and product not in seen:
            matched.append(product)
            seen.add(product)
    return matched


def match_caption_keywords(caption: str, keyword_list: List[str]) -> List[str]:
    """从 caption 中匹配关键词列表，返回命中的关键词（用于部件/状态/图示抽取）。"""
    return [kw for kw in keyword_list if kw in caption]
